/**
 * Helper to convert UTC Date to Egypt Date string YYYY-MM-DD
 */
export function getEgyptDateString(d = new Date()) {
    return new Intl.DateTimeFormat('en-CA', {
        timeZone: 'Africa/Cairo',
        year: 'numeric',
        month: '2-digit',
        day: '2-digit'
    }).format(d);
}

